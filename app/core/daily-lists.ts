import fs from "node:fs/promises";
import { dayInZone, validDate } from "./dates";
import { byPriority } from "./task-views";
import type { Diagnostic, Task } from "./model";
import { hash } from "./notes";

const marker = "<!-- todo:daily-list:v1 -->\n";
const markdown = (value: string) =>
  value.replace(/\s+/g, " ").replace(/[\\`*_[\]<>~|]/g, "\\$&");
const taskLink = (task: Task) => {
  const target = task.path
    .split("/")
    .map((part) =>
      encodeURIComponent(part).replace(
        /[!'()*]/g,
        (char) => "%" + char.charCodeAt(0).toString(16).toUpperCase(),
      ),
    )
    .join("/");
  const link = `[${markdown(task.title)}](../${target})`;
  return task.status === "done" ? `- ~~${link}~~` : `- ${link}`;
};

type DailyLists = {
  tasks: Task[];
  today: string;
  timezone: string;
  diagnostics: Diagnostic[];
};

// These are disposable views of the task notes, never another source of truth.
// Keep old empty day pages so a moved task disappears without deleting files.
export async function syncDailyLists(
  input: DailyLists,
  safe: (relative: string) => Promise<string>,
  atomic: (file: string, raw: string) => Promise<void>,
): Promise<Diagnostic[]> {
  const issues: Diagnostic[] = [];
  const issue = (name: string, message: string) =>
    issues.push({
      id: hash("daily-list:" + name),
      path: "Days/" + name,
      message,
      adoptable: false,
      revision: "",
    });
  const directory = await safe("Days");
  await fs.mkdir(directory, { recursive: true });
  const existing = new Map<string, string>();
  const blocked = new Set<string>();
  const days = new Set([input.today]);
  for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
    const day = entry.name.replace(/\.md$/, "");
    if (
      !["README.md", "Unscheduled.md"].includes(entry.name) &&
      !(entry.name.endsWith(".md") && validDate(day))
    )
      continue;
    try {
      if (!entry.isFile() || entry.isSymbolicLink())
        throw new Error("Use an ordinary generated Markdown file.");
      const raw = await fs.readFile(await safe("Days/" + entry.name), "utf8");
      if (!raw.startsWith(marker))
        throw new Error(
          "This filename is reserved for a Todo daily list. Move this note to regenerate the list.",
        );
      existing.set(entry.name, raw);
      if (validDate(day)) days.add(day);
    } catch (error) {
      blocked.add(entry.name);
      issue(entry.name, (error as Error).message);
    }
  }

  const groups = new Map<string, Task[]>();
  for (const task of input.tasks) {
    if (task.trashed) continue;
    const day =
      task.status === "done"
        ? task.completedAt
          ? dayInZone(new Date(task.completedAt), input.timezone)
          : "Unscheduled"
        : (task.scheduled ?? task.due ?? "Unscheduled");
    if (day !== "Unscheduled") days.add(day);
    const tasks = groups.get(day) ?? [];
    tasks.push(task);
    groups.set(day, tasks);
  }
  const write = async (name: string, raw: string) => {
    if (blocked.has(name) || existing.get(name) === raw) return;
    try {
      await atomic(await safe("Days/" + name), raw);
    } catch {
      issue(name, "Daily list could not be updated. Check its permissions.");
    }
  };
  const dates = [...days].sort().reverse();
  for (const day of [...dates, "Unscheduled"]) {
    const tasks = (groups.get(day) ?? []).sort(
      (a, b) =>
        Number(a.status === "done") - Number(b.status === "done") ||
        byPriority(a, b),
    );
    const warning =
      input.diagnostics.length || issues.length
        ? "> Some notes need attention; this list may be incomplete. See [day lists](README.md) and Todo vault status.\n\n"
        : "";
    const description =
      day === "Unscheduled"
        ? "Tasks without a planned date or deadline. Completed tasks here have no recorded completion date."
        : `Planned tasks and tasks completed on this day. Timezone: ${input.timezone}.`;
    await write(
      day + ".md",
      `${marker}# ${day === "Unscheduled" ? "Unscheduled tasks" : "Tasks · " + day}\n\n${description}\n\nGenerated by Todo. Edit the [linked task notes](../Tasks/), not this list. [All days](README.md).\n\n${warning}${tasks.length ? tasks.map(taskLink).join("\n") : "No tasks for this day."}\n`,
    );
  }
  const allIssues = [...input.diagnostics, ...issues];
  const counts = (day: string) => {
    const tasks = groups.get(day) ?? [];
    const done = tasks.filter((task) => task.status === "done").length;
    return `${tasks.length - done} open, ${done} completed`;
  };
  await write(
    "README.md",
    `${marker}# Day-by-day tasks\n\nOpen a date below, or read \`Days/YYYY-MM-DD.md\` directly. Dates use ${input.timezone}; today is ${input.today}.\n\n${dates.map((day) => `- [${day}](${day}.md)${day === input.today ? " (today)" : ""} — ${counts(day)}`).join("\n")}\n- [Unscheduled](Unscheduled.md) — ${counts("Unscheduled")}\n\nNormal links are open tasks; ~~struck-through links~~ are completed tasks. Open tasks use their planned date, or their deadline if no plan is set. Completed tasks use their actual completion day. Tasks moved or rolled to another day disappear from the earlier list. Trashed tasks are excluded.\n\nThese lists are generated while the Todo server is running and refreshed after task edits, rollover and restart. They are read-only summaries: edit the linked task note or use Todo. Task notes remain the source of truth; list edits do not change tasks.\n${allIssues.length ? "\n## Needs attention\n\n" + allIssues.map((d) => `- ${markdown(d.path)}: ${markdown(d.message)}`).join("\n") + "\n" : ""}`,
  );
  return issues;
}
